  // ====== Генератор персонажа ======
  const names = ['Алиара','Мирон','Элси','Кай','Талия','Рив','Серен','Фарос'];
  const looks = ['светлые волосы и веснушками','тёмные локоны и серьёзный взгляд','короткие стриженные волосы, как у скитальца','длинные косы, украшенные нитями']
  const traits = ['смелость, что блистает как броня','скрытность, как у ночного волка','любознательность, что не отпускает','мягкость, что лечит раны']

  function genChar(){
    const name = names[Math.floor(Math.random()*names.length)];
    const look = looks[Math.floor(Math.random()*looks.length)];
    const trait = traits[Math.floor(Math.random()*traits.length)];
    return {name,desc:`${name}, ${look}, отличающийся ${trait}.`}
  }

  // ====== Простой рендер и логика ======
  const textEl = document.getElementById('text');
  const choicesEl = document.getElementById('choices');
  const genBtn = document.getElementById('genCharBtn');
  const charBox = document.getElementById('charBox');
  const charName = document.getElementById('charName');
  const charDesc = document.getElementById('charDesc');
  const restartBtn = document.getElementById('restartBtn');
  const shareBtn = document.getElementById('shareBtn');

  let state = { current: 'start', char: null };

  function renderScene(id){
    const node = scenes[id];
    if(!node) return;
    state.current = id;
    renderText(node.text);
    renderChoices(node.choices);
    // update url hash so we can share link to current node
    history.replaceState(null, '', `#${id}`);
  }

  function renderText(t){
    // простой эффект печати: очищаем и печатаем по буквам
    textEl.innerHTML = '';
    let i=0;
    const speed = 8; // ms per char
    const timer = setInterval(()=>{
      textEl.innerHTML += t[i] || '';
      i++;
      if(i>t.length){clearInterval(timer)};
    }, speed);
  }

  function renderChoices(choices){
    choicesEl.innerHTML = '';
    if(!choices || choices.length===0){
      const endNote = document.createElement('div');
      endNote.className = 'text';
      endNote.textContent = '\nКонец пути. Нажми "Начать сначала", если хочешь пройти снова.';
      choicesEl.appendChild(endNote);
      return;
    }
    choices.forEach(c=>{
      const b = document.createElement('button');
      b.className = 'choiceBtn';
      b.textContent = c.t;
      b.addEventListener('click',()=>{
        // небольшая задержка для плавности
        setTimeout(()=>renderScene(c.to),120);
      });
      choicesEl.appendChild(b);
    });
  }

  genBtn.addEventListener('click',()=>{
    const c = genChar();
    state.char = c;
    charName.textContent = c.name;
    charDesc.textContent = c.desc;
    charBox.classList.remove('hidden');
  });

  restartBtn.addEventListener('click',()=>{
    // сгенерировать новый старт
    state.current='start';
    renderScene('start');
  });

  shareBtn.addEventListener('click',()=>{
    const url = location.href;
    navigator.clipboard?.writeText(url).then(()=>{
      shareBtn.textContent = 'Ссылка скопирована ✅';
      setTimeout(()=>shareBtn.textContent='Скопировать ссылку (в буфер)',1500);
    }).catch(()=>{
      alert('Не удалось скопировать — скопируй ссылку вручную: ' + url);
    })
  });

  // начальная загрузка: если в hash есть сцена — откроем её
  document.addEventListener('DOMContentLoaded',()=>{
    const hash = location.hash.replace('#','');
    if(hash && scenes[hash]) renderScene(hash);
    else renderScene('start');
  });

